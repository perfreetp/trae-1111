export const searchDrugs = (keyword: string): DrugLibraryItem[] => {
  if (!keyword.trim()) return [];
  const lowerKeyword = keyword.toLowerCase();
  return drugLibrary.filter(
    (drug) =>
      drug.drugName.toLowerCase().includes(lowerKeyword) ||
      drug.spec.toLowerCase().includes(lowerKeyword) ||
      drug.category.toLowerCase().includes(lowerKeyword)
  );
};
